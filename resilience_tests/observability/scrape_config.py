"""Prometheus's scrape configuration, generated from the environment profiles -- so a target's
address is written once, in envs/, and every target carries the labels the harness selects by
(env = profile name, node = node name; metrics.py, the dashboard's variables).

    python -m resilience_tests.observability.scrape_config --env e2-dedicated-vm-u22-2 \
        [--env another-profile ...] [--out ~/monitoring/prometheus.yml]

Only profiles with an `observability:` section contribute; each of their nodes gets one target
per exporter the section lists (job = exporter name, address = the node's SSH host). Then
reload Prometheus: curl -X POST localhost:9090/-/reload (started with --web.enable-lifecycle).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from resilience_tests.control.profile import EnvProfile, load_profile

HEADER = ("# Generated by: python -m resilience_tests.observability.scrape_config -- edit the env profiles,\n"
          "# not this file. Context only (Arch §7.1): nothing the harness judges comes from here.\n")


def build(profiles: list[EnvProfile]) -> dict[str, Any]:
    observed = [p for p in profiles if p.observability is not None]
    if not observed:
        raise ValueError("none of these profiles has an `observability:` section")
    interval = min(p.observability.scrape_interval_s for p in observed)  # type: ignore[union-attr]
    jobs: dict[str, list[dict[str, Any]]] = {}
    for profile in observed:
        assert profile.observability is not None
        for exporter, port in sorted(profile.observability.exporters.items()):
            for node in profile.nodes:
                jobs.setdefault(exporter, []).append(
                    {"targets": [f"{node.ssh.host}:{port}"], "labels": {"env": profile.name, "node": node.name}})
    seconds = f"{interval:g}s"
    return {
        "global": {"scrape_interval": seconds, "scrape_timeout": seconds},   # Arch §9: 1 s in test windows
        "scrape_configs": [{"job_name": "prometheus", "static_configs": [{"targets": ["localhost:9090"]}]}]
        + [{"job_name": job, "static_configs": configs} for job, configs in sorted(jobs.items())],
    }


def render(profiles: list[EnvProfile]) -> str:
    return HEADER + yaml.safe_dump(build(profiles), sort_keys=False)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--env", action="append", required=True, help="environment profile name or path (repeatable)")
    ap.add_argument("--out", help="write here instead of standard output")
    args = ap.parse_args(argv)
    text = render([load_profile(e) for e in args.env])
    if args.out:
        Path(args.out).expanduser().write_text(text)
        print(f"wrote {args.out}; reload Prometheus: curl -X POST localhost:9090/-/reload")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
